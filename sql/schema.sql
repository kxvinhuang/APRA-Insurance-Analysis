-- schema.sql
-- Star schema for the APRA life insurance claims and disputes data.

DROP TABLE IF EXISTS fact_policy, fact_claims, fact_disputes, fact_industry CASCADE;
DROP TABLE IF EXISTS company_name_history, dim_company, dim_channel, dim_cover, dim_measure, dim_category, dim_date CASCADE;
DROP TABLE IF EXISTS stg_policy, stg_claims, stg_disputes, stg_industry, stg_company_names CASCADE;
 
-- ---------------------------------------------------------------------------------------------
-- Dimensions
-- ---------------------------------------------------------------------------------------------

-- one row per reporting date (30 Jun and 31 Dec). Each date covers the 12 months before it.
CREATE TABLE dim_date (
    date_key             DATE PRIMARY KEY,
    year                 INT     NOT NULL,
    month                INT     NOT NULL CHECK (month IN (6, 12)),
    period_label         TEXT    NOT NULL,   -- e.g. 'Jun 2026'
    is_calendar_year_end BOOLEAN NOT NULL    -- true for 31 Dec, handy for "one date per year" annual views
);

-- one row per insurer, keyed on ABN because company names change over time
-- the industry 'Total' company has no ABN
CREATE TABLE dim_company (
    company_id        INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    abn               TEXT UNIQUE,
    company_name      TEXT    NOT NULL,      -- the latest name used by this ABN
    is_industry_total BOOLEAN NOT NULL,
    CHECK ((abn IS NULL) = is_industry_total)
);

-- every name an ABN has used, with the dates it was used
CREATE TABLE company_name_history (
    company_id     INT     NOT NULL REFERENCES dim_company (company_id),
    company_name   TEXT    NOT NULL,
    first_date     DATE    NOT NULL,
    last_date      DATE    NOT NULL,
    is_latest_name BOOLEAN NOT NULL,
    PRIMARY KEY (company_id, company_name)
);

-- the Other sheet also has a 'Total' channel that overlaps the four real channels
CREATE TABLE dim_channel (
    channel_id       INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    channel_name     TEXT    NOT NULL UNIQUE,
    is_total_channel BOOLEAN NOT NULL
);

CREATE TABLE dim_cover (
    cover_id   INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    cover_name TEXT NOT NULL UNIQUE
);

-- claim outcomes, dispute outcomes and the reasons on the Other sheet
-- category_id 0 means 'no category' so the fact tables never need a NULL category
-- the same category name can be a reason under more than one subject, which is why a fact row
-- always pairs a category with a measure (subject + data item)
CREATE TABLE dim_category (
    category_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name     TEXT    NOT NULL UNIQUE,
    is_total_category BOOLEAN NOT NULL       -- 'Total' contains the reasons around it, never add them together
);

-- what is being measured: a subject plus a data item, each with exactly one unit and calculation basis
CREATE TABLE dim_measure (
    measure_id        INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    subject           TEXT    NOT NULL,
    data_item         TEXT    NOT NULL,
    calculation_basis TEXT    NOT NULL,
    unit              TEXT    NOT NULL,
    is_additive       BOOLEAN NOT NULL,      -- counts and dollar totals can be summed, rates and averages cannot
    UNIQUE (subject, data_item)
);

-- ---------------------------------------------------------------------------------------------
-- Facts
-- value_status says why a value has no number: 'masked' or 'missing'
-- masked and missing are NULL, never 0
-- ---------------------------------------------------------------------------------------------

CREATE TABLE fact_policy (
    date_key         DATE    NOT NULL REFERENCES dim_date (date_key),
    company_id       INT     NOT NULL REFERENCES dim_company (company_id),
    channel_id       INT     NOT NULL REFERENCES dim_channel (channel_id),
    cover_id         INT     NOT NULL REFERENCES dim_cover (cover_id),
    measure_id       INT     NOT NULL REFERENCES dim_measure (measure_id),
    value_num        NUMERIC,
    value_status     TEXT    NOT NULL CHECK (value_status IN ('value', 'masked', 'missing')),
    is_invalid_combo BOOLEAN NOT NULL,
    is_out_of_range  BOOLEAN NOT NULL,
    PRIMARY KEY (date_key, company_id, channel_id, cover_id, measure_id),
    CHECK ((value_status = 'value') = (value_num IS NOT NULL))
);

CREATE TABLE fact_claims (
    date_key         DATE    NOT NULL REFERENCES dim_date (date_key),
    company_id       INT     NOT NULL REFERENCES dim_company (company_id),
    channel_id       INT     NOT NULL REFERENCES dim_channel (channel_id),
    cover_id         INT     NOT NULL REFERENCES dim_cover (cover_id),
    measure_id       INT     NOT NULL REFERENCES dim_measure (measure_id),
    category_id      INT     NOT NULL REFERENCES dim_category (category_id),
    value_num        NUMERIC,
    value_status     TEXT    NOT NULL CHECK (value_status IN ('value', 'masked', 'missing')),
    is_invalid_combo BOOLEAN NOT NULL,
    is_out_of_range  BOOLEAN NOT NULL,
    PRIMARY KEY (date_key, company_id, channel_id, cover_id, measure_id, category_id),
    CHECK ((value_status = 'value') = (value_num IS NOT NULL))
);

CREATE TABLE fact_disputes (
    date_key         DATE    NOT NULL REFERENCES dim_date (date_key),
    company_id       INT     NOT NULL REFERENCES dim_company (company_id),
    channel_id       INT     NOT NULL REFERENCES dim_channel (channel_id),
    cover_id         INT     NOT NULL REFERENCES dim_cover (cover_id),
    measure_id       INT     NOT NULL REFERENCES dim_measure (measure_id),
    category_id      INT     NOT NULL REFERENCES dim_category (category_id),
    value_num        NUMERIC,
    value_status     TEXT    NOT NULL CHECK (value_status IN ('value', 'masked', 'missing')),
    is_invalid_combo BOOLEAN NOT NULL,
    is_out_of_range  BOOLEAN NOT NULL,
    PRIMARY KEY (date_key, company_id, channel_id, cover_id, measure_id, category_id),
    CHECK ((value_status = 'value') = (value_num IS NOT NULL))
);

-- the Other sheet: industry-level only, so there is no company
CREATE TABLE fact_industry (
    date_key         DATE    NOT NULL REFERENCES dim_date (date_key),
    channel_id       INT     NOT NULL REFERENCES dim_channel (channel_id),
    cover_id         INT     NOT NULL REFERENCES dim_cover (cover_id),
    measure_id       INT     NOT NULL REFERENCES dim_measure (measure_id),
    category_id      INT     NOT NULL REFERENCES dim_category (category_id),
    value_num        NUMERIC,
    value_status     TEXT    NOT NULL CHECK (value_status IN ('value', 'masked', 'missing')),
    is_invalid_combo BOOLEAN NOT NULL,
    is_out_of_range  BOOLEAN NOT NULL,
    PRIMARY KEY (date_key, channel_id, cover_id, measure_id, category_id),
    CHECK ((value_status = 'value') = (value_num IS NOT NULL))
);

-- ---------------------------------------------------------------------------------------------
-- Staging tables: the cleaned csv files are copied in exactly as they are into these tables, then load.sql
-- builds the dimensions and facts from them. Column names match the csv headers.
-- ---------------------------------------------------------------------------------------------

CREATE TABLE stg_policy (
    reporting_date    DATE, company_name TEXT, abn TEXT, subject TEXT, channel_type TEXT, cover_type TEXT,
    data_item         TEXT, calculation_basis TEXT, unit TEXT, value_num NUMERIC, value_status TEXT,
    is_industry_total BOOLEAN, is_invalid_combo BOOLEAN, is_out_of_range BOOLEAN
);

CREATE TABLE stg_claims (
    reporting_date    DATE, company_name TEXT, abn TEXT, subject TEXT, channel_type TEXT, cover_type TEXT,
    category          TEXT, data_item TEXT, calculation_basis TEXT, unit TEXT, value_num NUMERIC, value_status TEXT,
    is_industry_total BOOLEAN, is_invalid_combo BOOLEAN, is_out_of_range BOOLEAN
);

CREATE TABLE stg_disputes (LIKE stg_claims);

CREATE TABLE stg_industry (
    reporting_date    DATE, subject TEXT, channel_type TEXT, cover_type TEXT, category TEXT,
    data_item         TEXT, calculation_basis TEXT, unit TEXT, value_num NUMERIC, value_status TEXT,
    is_invalid_combo  BOOLEAN, is_out_of_range BOOLEAN, is_total_channel BOOLEAN, is_total_category BOOLEAN
);

CREATE TABLE stg_company_names (
    abn TEXT, company_name TEXT, first_date DATE, last_date DATE, is_latest_name BOOLEAN
);